const assert=require('node:assert/strict');
const sim=require('../game-simulation.js');
globalThis.SootSeedSimulation=sim;
require('../level-lab/types.js');require('../level-lab/rng.js');require('../level-lab/candidates.js');require('../level-lab/validation.js');require('../level-lab/mutations.js');require('../level-lab/solver.js');require('../level-lab/evaluation.js');
require('../level-lab/agents.js');
const level={name:'Smoke',moves:2,req:{wood:0,charcoal:1},tools:['wait','woodcutter'],map:['FT.','...']};
const original=JSON.parse(JSON.stringify(level));
const candidate=SootSeedLevelLabCandidates.createCandidate('test',level,{id:'seed'});
assert.deepEqual(level,original,'loading a seed must not mutate the canonical definition');
const initial=sim.createInitialState(candidate.level);
assert.equal(initial.moves,2,'simulation initializes without UI');
const waited=sim.applyAction(candidate.level,initial,{tool:'wait'}).state;
assert.equal(waited.moves,2,'WAIT costs zero moves');
assert.equal(waited.actions,1,'WAIT advances one world step');
assert.equal(waited.cells[0][0].state,'dying-fire','WAIT advances active Fire');
const cloneA=SootSeedLevelLabCandidates.cloneCandidate(candidate,{id:'copy-a'}),cloneB=SootSeedLevelLabCandidates.cloneCandidate(candidate,{id:'copy-b'});
assert.deepEqual(cloneA.level,cloneB.level,'candidate cloning is deterministic');
assert.equal(SootSeedLevelLabValidation.validate({...level,fires:[{r:99,c:0,after:1}]}).ok,false,'invalid fire coordinates are rejected');
const a=SootSeedLevelLabRng.createSeededRng('repeat'),b=SootSeedLevelLabRng.createSeededRng('repeat');
assert.deepEqual([a.next(),a.next(),a.next()],[b.next(),b.next(),b.next()],'seeded RNG repeats');
const waitActions=SootSeedLevelLabSolver.canonicalActions(candidate.level,initial);
assert(waitActions.some(action=>action.tool==='wait'),'legal actions include WAIT when Fire is pending');
assert.equal(SootSeedLevelLabSolver.stateHash(initial),SootSeedLevelLabSolver.stateHash(sim.cloneState(initial)),'identical states have the same hash');
assert.notEqual(SootSeedLevelLabSolver.stateHash(initial),SootSeedLevelLabSolver.stateHash(waited),'WAIT changes the solver state identity');
const balanced=SootSeedLevelLabAgents.agents.find(agent=>agent.id==='balanced');
const pickA=SootSeedLevelLabAgents.chooseAction(balanced,candidate.level,initial,SootSeedLevelLabRng.createSeededRng('agent-repeat'));
const pickB=SootSeedLevelLabAgents.chooseAction(balanced,candidate.level,initial,SootSeedLevelLabRng.createSeededRng('agent-repeat'));
assert.deepEqual(pickA.action,pickB.action,'same agent state and seed choose the same action');
assert(sim.isLegalAction(candidate.level,initial,pickA.action),'agents choose only legal actions');
const ensembleA=SootSeedLevelLabAgents.runEnsemble(candidate.level,{attempts:3,seed:'ensemble-repeat'});
const ensembleB=SootSeedLevelLabAgents.runEnsemble(candidate.level,{attempts:3,seed:'ensemble-repeat'});
assert.deepEqual(ensembleA.map(x=>x.runs.map(run=>run.actions)),ensembleB.map(x=>x.runs.map(run=>run.actions)),'same ensemble seed repeats exactly');
assert.equal(ensembleA[0].runs.reduce((sum,run)=>sum+(run.firstAction?1:0),0),3,'first-action aggregation covers every attempt');
assert.deepEqual(level,original,'agent attempts do not mutate canonical level data');
const forgeLevel={name:'Forge',moves:1,req:{iron:1},tools:['forge'],map:['T.O','...']};
const forgeInitial=sim.createInitialState(forgeLevel),forgeFirst=SootSeedLevelLabAgents.agents.find(agent=>agent.id==='forge-first');
assert.equal(SootSeedLevelLabAgents.chooseAction(forgeFirst,forgeLevel,forgeInitial,SootSeedLevelLabRng.createSeededRng('forge')).action.tool,'forge','Forge First chooses a meaningful Forge opportunity');
const impossible={name:'Impossible',moves:1,req:{wood:1},tools:['wait'],map:['...']};
assert.equal(SootSeedLevelLabSolver.solveLevel(impossible).status,'UNSOLVABLE','deliberately impossible level is not solved');
assert.equal(SootSeedLevelLabSolver.solveLevel(candidate.level,{maxExploredStates:0}).status,'SEARCH_LIMIT_REACHED','search limits do not claim unsolvability');
console.log('Level Lab smoke tests passed.');
