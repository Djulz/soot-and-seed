const assert=require('node:assert/strict');
const sim=require('../game-simulation.js');
globalThis.SootSeedSimulation=sim;
require('../level-lab/types.js');require('../level-lab/rng.js');require('../level-lab/candidates.js');require('../level-lab/validation.js');require('../level-lab/mutations.js');require('../level-lab/solver.js');require('../level-lab/evaluation.js');
require('../level-lab/agents.js');
const level={name:'Smoke',moves:2,req:{wood:0,charcoal:1},tools:['wait','woodcutter'],map:['FT.','...']};
const original=JSON.parse(JSON.stringify(level));
const candidate=SootSeedLevelLabCandidates.createCandidate('test',level,{id:'seed'});
assert.deepEqual(level,original,'loading a seed must not mutate the canonical definition');
const initial=sim.createInitialState(candidate.level);
assert.equal(initial.moves,2,'simulation initializes without UI');
const waited=sim.applyAction(candidate.level,initial,{tool:'wait'}).state;
assert.equal(waited.moves,2,'WAIT costs zero moves');
assert.equal(waited.actions,1,'WAIT advances one world step');
assert.equal(waited.cells[0][0].state,'dying-fire','WAIT advances active Fire');
const cloneA=SootSeedLevelLabCandidates.cloneCandidate(candidate,{id:'copy-a'}),cloneB=SootSeedLevelLabCandidates.cloneCandidate(candidate,{id:'copy-b'});
assert.deepEqual(cloneA.level,cloneB.level,'candidate cloning is deterministic');
assert.equal(SootSeedLevelLabValidation.validate({...level,fires:[{r:99,c:0,after:1}]}).ok,false,'invalid fire coordinates are rejected');
const a=SootSeedLevelLabRng.createSeededRng('repeat'),b=SootSeedLevelLabRng.createSeededRng('repeat');
assert.deepEqual([a.next(),a.next(),a.next()],[b.next(),b.next(),b.next()],'seeded RNG repeats');
console.log('Level Lab smoke tests passed.');
