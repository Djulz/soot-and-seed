const assert=require('node:assert/strict');
require('../hex-lab.js');
const hex=globalThis.SootSeedHexLab;
assert.equal(hex.directions.length,6,'Hex Lab has exactly six axial directions');
assert.deepEqual(hex.neighbor(2,3,'NE'),[3,2],'NE uses the declared axial delta');
assert.equal(new Set(hex.neighbors(2,3).map(item=>hex.key(item.q,item.r))).size,6,'every hex has six distinct neighbor coordinates');
const g=hex.geometry(40);
assert.equal(g.width/g.height,Math.sqrt(3)/2,'regular pointy-top hex ratio is preserved');
assert.equal(Math.hypot(hex.point(1,0,40).x,hex.point(1,0,40).y),Math.hypot(hex.point(1,-1,40).x,hex.point(1,-1,40).y),'all six neighbor centres are equidistant');
assert.equal(hex.directionForDrag(0,0,40),null,'central drag dead zone cancels direction selection');
assert.equal(hex.directionForDrag(70,0,40),'E','dragging beyond the dead zone snaps to a hex axis');
const a=hex.definitions.a,initial=hex.createInitialState(a),before=JSON.stringify(initial);
const cut=hex.cutLine(initial,1,2,'E');
assert.equal(cut.length,3,'directional Woodcutter is capped at three contiguous Trees');
const afterCut=hex.applyAction(a,initial,{tool:'woodcutter',q:1,r:2,direction:'E'}).state;
assert.equal(afterCut.moves,initial.moves-1,'Woodcutter costs one move');
assert.equal(afterCut.res.wood,3,'directional cut produces one Wood per Tree');
assert.equal(JSON.stringify(initial),before,'applying Hex Lab actions does not mutate prior state');
const waited=hex.applyAction(a,initial,{tool:'wait'}).state;
assert.equal(waited.moves,initial.moves,'WAIT costs zero moves');
assert.equal(waited.worldSteps,1,'WAIT advances exactly one Hex Lab world step');
assert.equal(Object.values(waited.cells).filter(cell=>cell.fire==='active').length>1,true,'an active Fire spreads through shared hex edges');
const charcoal=hex.applyAction(a,waited,{tool:'wait'}).state;
assert(charcoal.res.charcoal>0,'Tree charcoal is delayed until dying Fire becomes Burnt');
const wheat={id:'wheat',moves:1,req:{wheat:2},tools:['sickle'],cells:{'0,0':{q:0,r:0,object:'wheat',fire:'normal'},'1,0':{q:1,r:0,object:'wheat',fire:'normal'},'0,1':{q:0,r:1,object:null,fire:'normal'}}};
const sickled=hex.applyAction(wheat,hex.createInitialState(wheat),{tool:'sickle',q:0,r:0}).state;
assert.equal(sickled.res.wheat,2,'Sickle follows six-neighbor Wheat connectivity');
const c=hex.definitions.c,forge=hex.getLegalActions(c,hex.createInitialState(c)).find(action=>action.tool==='forge');
assert(forge,'Iron Grove exposes a legal six-neighbor Forge placement');
const forged=hex.applyAction(c,hex.createInitialState(c),forge).state;
assert(forged.res.iron>0,'Forge converts adjacent fuel Trees and connected Ore to Iron');
const centreTree=hex.forgePlan(hex.createInitialState(c),3,1);
assert(centreTree&&centreTree.fuel.every(cell=>!(cell.q===3&&cell.r===1)),'Forge centre never counts as fuel');
const wind={id:'wind',moves:0,req:{},tools:['wait'],wind:'E',cells:{'0,0':{q:0,r:0,terrain:'ground',object:'tree',fire:'active'},'1,0':{q:1,r:0,terrain:'ground',object:null,fire:'normal'},'2,0':{q:2,r:0,terrain:'ground',object:'tree',fire:'normal'}}};
const windState=hex.applyAction(wind,hex.createInitialState(wind),{tool:'wait'}).state;
assert.equal(windState.cells['2,0'].fire,'active','Wind reaches the second hex from the original active Fire');
assert.equal(hex.validateDefinition({...a,wind:'bad'}).ok,false,'invalid Wind directions are rejected');
assert.deepEqual(hex.counts(a,hex.createInitialState(a)),{woodcutter:72,forge:0,sickle:0,wait:true,total:73},'Test A action-space count is stable');
console.log('Hex Lab smoke tests passed.');
